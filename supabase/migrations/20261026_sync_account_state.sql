-- Persist account-owned app state and assistant conversations.
-- Existing pantry_item rows and the legacy ai_message table are untouched.
begin;

create table if not exists public.user_app_state (
  user_id uuid primary key references auth.users(id) on delete cascade,
  saved_recipe_ids text[] not null default '{}',
  liked_recipe_ids text[] not null default '{}',
  watched_recipe_ids text[] not null default '{}',
  recipe_preferences jsonb not null default '{}'::jsonb
    check (jsonb_typeof(recipe_preferences) = 'object'),
  metric boolean not null default false,
  spoil_reminders boolean not null default true,
  preferred_store text,
  zip_code text check (zip_code is null or zip_code ~ '^[0-9]{5}$'),
  updated_at timestamptz not null default now()
);

alter table public.user_app_state enable row level security;
drop policy if exists user_app_state_owner_all on public.user_app_state;
create policy user_app_state_owner_all on public.user_app_state
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
grant select, insert, update, delete on public.user_app_state to authenticated;

create table if not exists public.chat_conversations (
  conversation_id uuid primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (conversation_id, user_id)
);

create table if not exists public.chat_messages (
  message_id bigint generated by default as identity primary key,
  conversation_id uuid not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  sender text not null check (sender in ('user', 'assistant')),
  content_html text not null,
  created_at timestamptz not null default now(),
  foreign key (conversation_id, user_id)
    references public.chat_conversations (conversation_id, user_id)
    on delete cascade
);

create index if not exists chat_conversations_user_created_idx
  on public.chat_conversations (user_id, created_at desc);
create index if not exists chat_messages_conversation_created_idx
  on public.chat_messages (conversation_id, created_at);

alter table public.chat_conversations enable row level security;
alter table public.chat_messages enable row level security;
drop policy if exists chat_conversations_owner_all on public.chat_conversations;
create policy chat_conversations_owner_all on public.chat_conversations
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
drop policy if exists chat_messages_owner_all on public.chat_messages;
create policy chat_messages_owner_all on public.chat_messages
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
grant select, insert, update, delete on public.chat_conversations to authenticated;
grant select, insert, update, delete on public.chat_messages to authenticated;
grant usage, select on sequence public.chat_messages_message_id_seq to authenticated;

commit;
