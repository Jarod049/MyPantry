// Generates the Supabase seed for Reels from the built-in catalog.
//   npm run recipes:sql            -> rewrites supabase/migrations/20261103_recipe_reels.sql
// Re-running is safe: rows are upserted by recipe_id, so edits to recipes.js update the
// table and nothing a user saved is lost.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'recipes.js'), 'utf8'), sandbox);
const catalog = sandbox.window.MYPANTRY_RECIPES;

// The ten launch recipes still live in app.js; pull them in so the table is complete.
const appSrc = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const start = appSrc.indexOf('const BASE_RECIPES = [');
const end = appSrc.indexOf('\n];', start);
const base = vm.runInNewContext('(' + appSrc.slice(start + 'const BASE_RECIPES = '.length, end + 2) + ')');

const recipes = [...base, ...catalog];
const ids = new Set();
for (const r of recipes) {
  if (!/^[a-z0-9-]+$/.test(r.id)) throw new Error(`Bad recipe id: ${r.id}`);
  if (ids.has(r.id)) throw new Error(`Duplicate recipe id: ${r.id}`);
  ids.add(r.id);
  if (!r.ing.length || !r.steps.length) throw new Error(`Recipe ${r.id} needs ingredients and steps`);
}

const q = s => s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`;
const arr = a => `array[${a.map(q).join(',')}]::text[]`;
const json = v => `${q(JSON.stringify(v))}::jsonb`;
const values = recipes.map((r, i) => `  (${[
  q(r.id), q(r.name), q(r.emoji), q(r.type), q(r.main), r.time, r.serves, r.likes || 0, q(r.bg),
  arr(r.kw || []), json(r.ing), arr(r.steps), r.subs ? json(r.subs) : 'null', i
].join(', ')})`).join(',\n');

const sql = `-- Recipe Reels catalog. Generated by scripts/recipes-sql.cjs from recipes.js and app.js.
-- Do not edit the INSERT by hand: change recipes.js and run \`npm run recipes:sql\`.
-- To add reels later without redeploying, insert rows into public.recipe with is_published = true.
begin;

create table if not exists public.recipe (
  recipe_id text primary key check (recipe_id ~ '^[a-z0-9-]+$'),
  name text not null check (length(name) between 1 and 120),
  emoji text not null default '🍽️',
  cuisine text not null,
  main_ingredient text not null,
  minutes integer not null check (minutes between 1 and 240),
  serves integer not null check (serves between 1 and 24),
  base_likes integer not null default 0 check (base_likes >= 0),
  background text,
  keywords text[] not null default '{}',
  ingredients jsonb not null check (jsonb_typeof(ingredients) = 'array' and jsonb_array_length(ingredients) > 0),
  steps text[] not null check (cardinality(steps) > 0),
  substitutions jsonb check (substitutions is null or jsonb_typeof(substitutions) = 'object'),
  video_url text check (video_url is null or video_url ~ '^https://'),
  sort_order integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists recipe_published_order_idx on public.recipe (is_published, sort_order);

-- Everyone (signed in or not) may read published reels; only the service role can write.
alter table public.recipe enable row level security;
drop policy if exists recipe_public_read on public.recipe;
create policy recipe_public_read on public.recipe for select to anon, authenticated using (is_published);
revoke insert, update, delete on public.recipe from anon, authenticated;
grant select on public.recipe to anon, authenticated;

insert into public.recipe (recipe_id, name, emoji, cuisine, main_ingredient, minutes, serves, base_likes, background,
  keywords, ingredients, steps, substitutions, sort_order) values
${values}
on conflict (recipe_id) do update set
  name = excluded.name, emoji = excluded.emoji, cuisine = excluded.cuisine,
  main_ingredient = excluded.main_ingredient, minutes = excluded.minutes, serves = excluded.serves,
  base_likes = excluded.base_likes, background = excluded.background, keywords = excluded.keywords,
  ingredients = excluded.ingredients, steps = excluded.steps, substitutions = excluded.substitutions,
  sort_order = excluded.sort_order, updated_at = now();

commit;
`;
const out = path.join(root, 'supabase/migrations/20261103_recipe_reels.sql');
fs.writeFileSync(out, sql);
console.log(`Wrote ${recipes.length} recipes to ${path.relative(root, out)}`);
